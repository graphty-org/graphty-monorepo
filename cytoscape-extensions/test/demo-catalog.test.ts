import { storyNameFromExport } from "storybook/internal/csf";
import { describe, expect, it } from "vitest";

import { ALGORITHM_NAMES, LAYOUT_NAMES } from "../src/index.js";
import { GENERATORS } from "../src/samples.js";
import {
    ALGORITHM_GROUPS,
    GALLERY_PAGES,
    type GalleryPage,
    GENERATOR_FAMILIES,
    GENERATOR_PRESETS,
    PAGE_TITLES,
    pageId,
    SIMULATION_LAYOUTS,
    STATIC_LAYOUTS,
    tileExportName,
    tileLabel,
} from "../stories/catalog.js";

// The Storybook demo offers what its catalog lists; these keep the catalog in step with what the extension registers,
// so a new layout, algorithm or generator cannot ship without a way to run it in the demo.
describe("the demo catalog", () => {
    it("lists every layout once", () => {
        expect([...SIMULATION_LAYOUTS, ...STATIC_LAYOUTS].sort()).toEqual([...LAYOUT_NAMES].sort());
    });

    it("lists every algorithm in exactly one group", () => {
        const listed = Object.values(ALGORITHM_GROUPS).flatMap((g) =>
            g.algorithms.map((a) => `graphty${a.charAt(0).toUpperCase()}${a.slice(1)}`),
        );
        expect(listed.sort()).toEqual([...ALGORITHM_NAMES].sort());
    });

    it("has a preset for every generator", () => {
        expect(Object.keys(GENERATOR_PRESETS).sort()).toEqual(Object.keys(GENERATORS).sort());
    });

    it("puts every generator in exactly one family", () => {
        expect(Object.values(GENERATOR_FAMILIES).flat().sort()).toEqual(Object.keys(GENERATORS).sort());
    });

    it("gives every tile a readable name", () => {
        for (const page of Object.keys(GALLERY_PAGES) as GalleryPage[]) {
            for (const key of GALLERY_PAGES[page]) {
                expect(tileLabel(page, key), `${page}/${key}`).toMatch(/^[A-Z]/);
            }
        }
    });
});

const HEADER = [
    "// THIS FILE IS AUTO GENERATED: DO NOT EDIT THIS FILE. INSTEAD EDIT stories/catalog.ts, then run",
    "// `npx vitest run test/demo-catalog.test.ts -u` (the test writes this file from the catalog).",
    'import type { Meta, StoryObj } from "@storybook/html-vite";',
    "",
];

/**
 * The story of one tile. The export name is the one the tile was first published under, so its story id never
 * changes; the story's name is what the sidebar shows.
 * @param page - the page
 * @param key - the tile
 * @returns the export
 */
function tileStory(page: GalleryPage, key: string): string {
    const id = tileExportName(page, key)
        .split(/[^A-Za-z0-9]+/)
        .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
        .join("");
    // A name Storybook would show anyway (its name for the export) is left out.
    const label = tileLabel(page, key);
    const name = label === storyNameFromExport(id) ? "" : `    name: ${JSON.stringify(label)},\n`;
    return `export const ${id}: Story = {\n    ...tile("${page}", "${key}"),\n${name}};\n`;
}

/**
 * One story file: its meta (the title the reader sees, and the component id the stories were first published
 * under) and its stories.
 * @param from - the import path of gallery-stories
 * @param page - the page
 * @param title - the title
 * @param stories - the story exports
 * @param metaLines - more lines of the meta, after its id
 * @returns the file's text
 */
function storyFile(
    from: string,
    page: GalleryPage,
    title: string,
    stories: string[],
    metaLines: string[] = [],
): string {
    const imports = ["overview", "pageParameters", "tile"]
        .filter((name) => name === "pageParameters" || stories.some((s) => s.includes(`${name}(`)))
        .join(", ");
    return [
        ...HEADER,
        `import { ${imports} } from "${from}";`,
        "",
        "const meta: Meta = {",
        `    title: ${JSON.stringify(title)},`,
        `    id: ${JSON.stringify(pageId(page))},`,
        ...metaLines,
        `    parameters: pageParameters(${JSON.stringify(page)}),`,
        "};",
        "export default meta;",
        "",
        "type Story = StoryObj;",
        "",
        stories.join("\n"),
    ].join("\n");
}

const sideBySide = (page: GalleryPage): string =>
    `export const Overview: Story = {\n    ...overview("${page}"),\n    name: "Side by side",\n};\n`;

/**
 * Every story file the catalog makes, by path: one per page, holding its "Side by side" story and one story per
 * tile, except the generators, whose tiles are split into one file per family beside the page's own file.
 * @returns the files' texts by path
 */
function galleryFiles(): Record<string, string> {
    const files: Record<string, string> = {};
    for (const page of Object.keys(GALLERY_PAGES) as GalleryPage[]) {
        const tiles = page === "Generators" ? [] : GALLERY_PAGES[page].map((key) => tileStory(page, key));
        files[`${page}.stories.ts`] = storyFile("../gallery-stories.js", page, PAGE_TITLES[page], [
            sideBySide(page),
            ...tiles,
        ]);
    }
    for (const [family, names] of Object.entries(GENERATOR_FAMILIES)) {
        const file = family
            .split(/[^A-Za-z]+/)
            .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
            .join("");
        files[`generators/${file}.stories.ts`] = storyFile(
            "../../gallery-stories.js",
            "Generators",
            `Data/Generators/${family}`,
            names.map((key) => tileStory("Generators", key)),
            [
                "    // The Generators overview story documents the family pages; they add no Docs page.",
                '    tags: ["!autodocs"],',
            ],
        );
    }
    return files;
}

// One story per gallery tile: a catalog entry without its story fails here. After changing the catalog,
// `npx vitest run test/demo-catalog.test.ts -u` rewrites the story files.
describe("the gallery stories", () => {
    for (const [path, text] of Object.entries(galleryFiles())) {
        it(`writes stories/gallery/${path}`, async () => {
            await expect(text).toMatchFileSnapshot(`../stories/gallery/${path}`);
        });
    }
});
