/** How tall Dialog's line box is, in ems: what getStringBounds gives as a string's height. */
export const DIALOG_LINE_HEIGHT = 1.1640625;

/**
 * How wide Dialog draws a text, in ems.
 * @param text - the text
 * @returns its advance width
 */
export function dialogWidth(text: string): number {
    let sum = 0;
    for (const ch of text) {
        const c = ch.codePointAt(0) ?? 0;
        // ponytail: a character outside the table (CJK and other scripts Java falls back to another font for) is
        // counted a full em; a measured table per script when a sample needs it
        if (c >= 32 && c < 127) {
            sum += ASCII[c - 32];
        } else {
            sum += c >= 160 && c < 0x250 ? LATIN[c - 160] : 1000;
        }
    }
    return sum / 1000;
}
