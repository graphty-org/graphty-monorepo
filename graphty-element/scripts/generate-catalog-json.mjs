#!/usr/bin/env node
/**
 * Emits `dist/graphty-catalog.json`: everything the element can do, as one plain-JSON file.
 *
 * The descriptor tables in `src/catalog/` are already plain data by construction -- no classes,
 * no methods, no library objects -- so this script does no transformation. It imports the BUILT
 * modules, which means it publishes exactly what the package ships rather than what the source
 * tree says, and writes them out under one root with a version stamp.
 *
 * The point of the file is that an options form, a metrics panel, a file picker, a cost gate or
 * a coding agent can read the whole algorithm, layout, format, palette and scale surface -- with
 * every option each of them accepts -- without parsing TypeScript, installing a renderer or
 * hard-coding a list that falls silently out of step.
 *
 * Run by `npm run build`, after the Vite builds have produced `dist/`.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const distDir = resolve(packageRoot, "dist");
const outFile = resolve(distDir, "graphty-catalog.json");

/**
 * Imports one built entry point of this package.
 * @param {string} file The file name under `dist/`, for example `catalog.js`.
 * @returns {Promise<Record<string, unknown>>} The module's exports.
 * @throws {Error} When the file is missing, which means the build has not run yet.
 */
async function importBuilt(file) {
    const path = resolve(distDir, file);

    try {
        return await import(pathToFileURL(path).href);
    } catch (cause) {
        throw new Error(`Cannot read dist/${file}. Run the Vite build before this script.`, { cause });
    }
}

const manifest = JSON.parse(readFileSync(resolve(packageRoot, "package.json"), "utf8"));
const catalog = await importBuilt("catalog.js");
const session = await importBuilt("session.js");

const document = {
    $generated:
        "THIS FILE IS AUTO GENERATED: DO NOT EDIT THIS FILE. INSTEAD EDIT the descriptor tables " +
        "in graphty-element/src/catalog/ AND RUN graphty-element/scripts/generate-catalog-json.mjs " +
        "(it runs as part of `npm run build`).",
    package: manifest.name,
    version: manifest.version,

    /** Every algorithm the element can run, with its result shape, fields and options. */
    algorithms: catalog.BUILT_IN_ALGORITHMS,

    /** Every layout the element can arrange a graph with, with its engine and options. */
    layouts: catalog.LAYOUT_DESCRIPTORS,

    /** Every file format the element can import or export, with its options. */
    formats: catalog.FORMAT_DESCRIPTORS,

    /** Every colour palette, with its colours and which colour-vision deficiencies it survives. */
    palettes: catalog.PALETTE_DESCRIPTORS,

    /** Every scale that maps a data range onto a visual channel. */
    scales: catalog.SCALE_DESCRIPTORS,

    /** Named things a caller may reasonably ask for that no implementation serves, and why. */
    unserved: {
        layouts: catalog.UNSERVED_LAYOUT_IDS,
        formats: catalog.UNSERVED_FORMAT_IDS,
    },

    /** The result shapes an algorithm can produce; a field's `path` is relative to one of these. */
    resultShapes: catalog.RESULT_SHAPES,

    /** Every error code the element reports. The code is the contract; the message is not. */
    errorCodes: session.GRAPHTY_ERROR_CODES,
};

for (const [key, value] of Object.entries(document)) {
    if (Array.isArray(value) && value.length === 0) {
        throw new Error(`The catalogue's "${key}" table is empty. Refusing to publish an empty catalogue.`);
    }
}

writeFileSync(outFile, `${JSON.stringify(document, null, 2)}\n`, "utf8");

const counts = ["algorithms", "layouts", "formats", "palettes", "scales", "errorCodes"]
    .map((key) => `${document[key].length} ${key}`)
    .join(", ");

process.stdout.write(`graphty-catalog.json: ${counts}\n`);
