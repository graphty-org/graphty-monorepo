#!/usr/bin/env node
/**
 * Writes `build/doors.json`: the door list of `src/session/commands/doors.ts` as plain JSON.
 *
 * The graphty app's lint rule `no-element-mutation` (graphty/eslint-rules/) reads it to know
 * which public members of the element change project state. It goes to `build/`, not `dist/`,
 * because `dist/` is published and the door list, with its known gaps, is not public API.
 * `build/` is git-ignored and not in package.json `files`.
 *
 * The door list is read from source with Node's TypeScript type stripping (the module has only
 * type imports), because no entry point exports it. Functions in the list (how the doors tests
 * call a door) are dropped by `JSON.stringify`; the rule reads only names and kinds.
 *
 * Run by `npm run build`.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = resolve(packageRoot, "build/doors.json");

const { DOOR_ROOTS } = await import(pathToFileURL(resolve(packageRoot, "src/session/commands/doors.ts")).href);

const document = {
    $generated:
        "THIS FILE IS AUTO GENERATED: DO NOT EDIT THIS FILE. INSTEAD EDIT " +
        "graphty-element/src/session/commands/doors.ts AND RUN graphty-element/scripts/write-doors-json.mjs " +
        "(it runs as part of `npm run build`).",
    roots: DOOR_ROOTS,
};

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, `${JSON.stringify(document, null, 1)}\n`);
