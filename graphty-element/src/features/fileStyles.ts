/**
 * @file What the `file-styles` experiment adds to the style catalog, as data.
 *
 * Drawing the styles other programs write into graph files (Cytoscape, yEd, Gephi, Graphviz,
 * Pajek, draw.io, vis-network and more) added style channels and values the element did not have
 * before. With the experiment off, `session.catalog.channels()` leaves the channels out and takes
 * the values out of the channels that stay, and a binding that spreads over a channel's values
 * spreads over the remaining ones. A layer that writes one of them directly is still drawn. Plain
 * data, free of Babylon.js, Lit and the DOM.
 */

