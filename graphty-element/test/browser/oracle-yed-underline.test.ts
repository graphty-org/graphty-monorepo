/**
 * The oracle comparison's SVG reader on yEd's underlined labels: ySVG writes each line of a label of
 * `underlinedText="true"` as a `<text>` and a level `<line>` just under its baseline, in the label's `<g>`
 * (graphml-stm32-func's `CS` labels). Read as lines of the drawing, each underline beside a node's border was read as
 * an edge from that node; it is lettering, which graphty draws with the words.
 */
import { assert, describe, it } from "vitest";

import { readSvgPrimitives } from "../fidelity/oracle/svg-primitives";

/**
 * A yEd label with a line beside it.
 * @param lineY - the line's height
 * @returns the SVG, written by ySVG
 */
function sheet(lineY: number): string {
    return `<svg xmlns="http://www.w3.org/2000/svg" width="200" height="200"><!--Generated by ySVG 2.5-->
        <g font-size="14px" stroke="black">
            <text x="20" y="50" xml:space="preserve" stroke="none">CS</text>
            <line x1="20" y1="${String(lineY)}" x2="40" y2="${String(lineY)}"/>
        </g></svg>`;
}

describe("the oracle SVG reader on yEd's underlined labels", () => {
    it("reads a line just under a label's baseline as no line of the drawing", () => {
        const { prims } = readSvgPrimitives(sheet(53.3));
        assert.deepEqual(
            prims.map((p) => p.kind),
            ["text"],
        );
    });

    it("still reads a line well clear of the words as a line", () => {
        const { prims } = readSvgPrimitives(sheet(120));
        assert.lengthOf(
            prims.filter((p) => p.tag === "line"),
            1,
        );
    });
});
