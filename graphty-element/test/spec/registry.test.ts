/**
 * @file The generated registries of spec/registry/ (spec/README.md 10.1): the vocabularies other
 * code owns -- algorithms, layouts, style channels and scales -- as graphty-element's catalog
 * declares them, keeping format facts only. The committed files must equal the projection; run
 * `npm run spec:registry` (UPDATE_SPEC_REGISTRY=1) to rewrite them. Also checks that renames
 * never reuse a name, and that the worked examples write only current, declared names.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";

import { assert, describe, it } from "vitest";

import { BUILT_IN_ALGORITHMS } from "../../src/catalog/algorithms";
import { LAYOUT_CATALOG, savedLayoutOptions } from "../../src/catalog/layouts";
import { SCALE_DESCRIPTORS } from "../../src/catalog/scales";
import type { FieldDescriptor, OptionDescriptor } from "../../src/catalog/types";
import { dimensionOptions } from "../../src/session/document2/codecs/viewParts";
import { CHANNEL_DESCRIPTORS } from "../../src/session/styles/channels";

const SPEC = new URL("../../spec/", import.meta.url);
const GENERATED =
    "THIS FILE IS AUTO GENERATED: DO NOT EDIT THIS FILE. INSTEAD EDIT graphty-element/src/catalog/ " +
    "(algorithms.ts, layouts.ts, scales.ts) or src/session/styles/channels.ts AND RUN npm run spec:registry";

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };
type JsonObject = Record<string, Json>;

/**
 * A JSON value as text: a string as it is, anything else as JSON.
 * @param value - The value.
 * @returns The text.
 */
const text = (value: Json | undefined): string => (typeof value === "string" ? value : JSON.stringify(value));

/**
 * A value as the file writes it: a non-finite number as its section 11 string, members left
 * undefined dropped.
 * @param value - The value.
 * @returns The JSON value.
 */
function json(value: unknown): Json {
    if (typeof value === "number") {
        return Number.isFinite(value) ? value : String(value);
    }

    if (Array.isArray(value)) {
        return value.map(json);
    }

    if (typeof value === "object" && value !== null) {
        return Object.fromEntries(
            Object.entries(value).flatMap(([key, held]) => (held === undefined ? [] : [[key, json(held)]])),
        );
    }

    return value as Json;
}

/**
 * The listed members of an object, in the listed order.
 * @param value - The object.
 * @param members - The members kept.
 * @returns The members present.
 */
function pick(value: object, members: readonly string[]): JsonObject {
    const held = value as Record<string, unknown>;
    return json(Object.fromEntries(members.map((member) => [member, held[member]]))) as JsonObject;
}

/**
 * A bound as the file writes it: a number, or the bound it is measured as.
 * @param bound - The bound.
 * @returns The value.
 */
const boundOf = (bound: OptionDescriptor["min"]): unknown =>
    typeof bound === "object" && bound !== null ? bound.from : bound;

/**
 * One option's format facts.
 * @param option - The option.
 * @returns Its entry.
 */
const optionOf = (option: OptionDescriptor): JsonObject =>
    pick(
        {
            ...option,
            min: boundOf(option.min),
            max: boundOf(option.max),
            values: option.values?.map((choice) => choice.value),
        },
        ["name", "type", "default", "min", "max", "step", "values", "on", "attributeType", "formerNames"],
    );

const FIELD_MEMBERS = [
    "name",
    "kind",
    "type",
    "unit",
    "normalization",
    "measurement",
    "directedOnly",
    "domain",
    "polarity",
    "order",
    "missing",
    "unstable",
];

/** What the registry files hold, by name, projected from the catalog. */
function projection(): Record<string, JsonObject> {
    const algorithms = BUILT_IN_ALGORITHMS.map((descriptor) => ({
        ...pick(
            {
                ...descriptor,
                approximable:
                    descriptor.approximable === undefined
                        ? undefined
                        : pick(descriptor.approximable, ["method", "defaultSample", "seeded"]),
            },
            ["key", "formerKeys", "shape", "scopeInput", "weightMeaning", "requires", "approximable"],
        ),
        options: descriptor.options.map(optionOf),
        fields: descriptor.fields.map((field: FieldDescriptor) => pick(field, FIELD_MEMBERS)),
    }));
    const layouts = LAYOUT_CATALOG.map(({ descriptor, implementations }) => {
        const saved = savedLayoutOptions(descriptor.id);
        const all = [implementations.find((each) => each.isDefault), ...implementations].flatMap(
            (each) => each?.options ?? [],
        );
        // An option the engine works out from the dimension is written only when asked (9 rule 10).
        const layoutOption = (option: OptionDescriptor, derived: ReadonlySet<string>): JsonObject => ({
            ...optionOf(option),
            ...(derived.has(option.name) ? { derivedFrom: "dimension" } : {}),
        });
        const defaultDerived = dimensionOptions(descriptor.engine);
        return {
            id: descriptor.id,
            maxDimensions: descriptor.maxDimensions,
            options: saved.map((name) =>
                layoutOption(
                    all.find((option) => option.name === name) ?? ({ name, type: "unknown" } as OptionDescriptor),
                    defaultDerived,
                ),
            ),
            engines: implementations.map((each) => ({
                engine: each.engine,
                options: each.options
                    .filter((option) => !saved.includes(option.name))
                    .map((option) => layoutOption(option, dimensionOptions(each.engine))),
            })),
        };
    });
    const channels = Object.values(CHANNEL_DESCRIPTORS).map((channel) =>
        pick({ ...channel, experimental: channel.feature }, [
            "channel",
            "target",
            "accepts",
            "values",
            "min",
            "exclusiveMin",
            "max",
            "integer",
            "step",
            "perWorldUnit",
            "experimental",
        ]),
    );
    const scales = SCALE_DESCRIPTORS.map((scale) => ({
        name: scale.name,
        domainKind: scale.domainKind,
        options: scale.options.map(optionOf),
    }));
    const file = (registry: string, member: string, entries: unknown[]): JsonObject => ({
        registry,
        version: 1,
        $generated: GENERATED,
        [member]: json(entries),
    });
    return {
        algorithms: file("algorithms", "algorithms", algorithms),
        layouts: file("layouts", "layouts", layouts),
        channels: file("channels", "channels", channels),
        scales: file("scales", "scales", scales),
    };
}

const REGISTRY = projection();
const registryUrl = (name: string): URL => new URL(`registry/${name}.json`, SPEC);

describe("the generated registries (README 10.1)", () => {
    for (const [name, wanted] of Object.entries(REGISTRY)) {
        it(`registry/${name}.json is what the catalog declares`, () => {
            if (process.env.UPDATE_SPEC_REGISTRY === "1") {
                writeFileSync(registryUrl(name), `${JSON.stringify(wanted, null, 4)}\n`);
            }

            const committed = JSON.parse(readFileSync(registryUrl(name), "utf8")) as JsonObject;
            assert.deepStrictEqual(committed, wanted, "run npm run spec:registry");
        });
    }
});

describe("scale option defaults are the format defaults builtins.md states (README 10.1 rule 3)", () => {
    it("gives every default a scale's Definition states the same value in registry/scales.json", () => {
        const builtins = readFileSync(new URL("builtins.md", SPEC), "utf8");
        const section = builtins.slice(builtins.indexOf("## Scales"), builtins.indexOf("## Camera controllers"));
        const scales = new Map(
            (REGISTRY.scales.scales as JsonObject[]).map((entry) => [
                entry.name as string,
                entry.options as JsonObject[],
            ]),
        );
        let checked = 0;
        for (const [, name, definition] of section.matchAll(/^\| `([a-z0-9]+)` +\|(.*)\|$/gm)) {
            for (const [, option, value] of definition.matchAll(/`([A-Za-z]+)` \(default ([^,)]+)/g)) {
                const listed = scales.get(name)?.find((each) => each.name === option);
                assert.isDefined(listed, `${name}.${option}`);
                assert.strictEqual(text(listed.default), value, `${name}.${option}`);
                checked += 1;
            }
        }

        for (const options of scales.values()) {
            const reverse = options.find((each) => each.name === "reverse");
            assert.isTrue(reverse === undefined || reverse.default === false, "reverse (default false)");
        }

        assert.isAtLeast(checked, 3);
    });
});

describe("renames never reuse a name (README 10.1 rules 1 and 2)", () => {
    const current = new Set<string>(BUILT_IN_ALGORITHMS.map((descriptor) => descriptor.key));

    it("gives no former key to a current key, nor to two entries", () => {
        const formers = BUILT_IN_ALGORITHMS.flatMap((descriptor) => (descriptor.formerKeys ?? []).map((f) => f.key));
        for (const key of formers) {
            assert.isFalse(current.has(key), key);
        }

        assert.strictEqual(new Set(formers).size, formers.length);
    });

    it("gives no option a former name that is another option's current name", () => {
        for (const descriptor of BUILT_IN_ALGORITHMS) {
            const names = new Set(descriptor.options.map((option) => option.name));
            for (const option of descriptor.options) {
                for (const former of option.formerNames ?? []) {
                    assert.isFalse(names.has(former), `${descriptor.key}.${former}`);
                }
            }
        }
    });
});

/**
 * Every section the examples hold, as a section file or inside a full file.
 * @returns The sections.
 */
function exampleSections(): JsonObject[] {
    const files = ["", "minimal/"].flatMap((dir) =>
        readdirSync(new URL(`examples/${dir}`, SPEC))
            .filter((file) => file.endsWith(".json"))
            .map((file) => `examples/${dir}${file}`),
    );
    return files.flatMap((file): JsonObject[] => {
        const doc = JSON.parse(readFileSync(new URL(file, SPEC), "utf8")) as JsonObject;
        return doc.kind === "graphty-document" ? (Object.values(doc.sections as JsonObject) as JsonObject[]) : [doc];
    });
}

/**
 * Every object anywhere in a value.
 * @param value - The value.
 * @returns The objects, outermost first.
 */
function objectsIn(value: Json | undefined): JsonObject[] {
    if (Array.isArray(value)) {
        return value.flatMap(objectsIn);
    }

    if (typeof value === "object" && value !== null) {
        return [value, ...Object.values(value).flatMap(objectsIn)];
    }

    return [];
}

describe("the examples write registry names (README 10.1)", () => {
    const sections = exampleSections();
    const ofKind = (kind: string): JsonObject[] => sections.filter((section) => section.kind === kind);
    const algorithms = new Map(
        (REGISTRY.algorithms.algorithms as JsonObject[]).map((entry) => [entry.key as string, entry]),
    );
    const layouts = new Map((REGISTRY.layouts.layouts as JsonObject[]).map((entry) => [entry.id as string, entry]));
    const channels = new Set((REGISTRY.channels.channels as JsonObject[]).map((entry) => entry.channel));
    const scales = new Set((REGISTRY.scales.scales as JsonObject[]).map((entry) => entry.name));

    /** Every run an example names: recipe algo.run, results runs, view run records, layer sources. */
    const runs = (): [string, JsonObject][] => [
        ...ofKind("graphty-recipe").flatMap((recipe) =>
            (recipe.commands as JsonObject[])
                .filter((command) => command.op === "algo.run")
                .map((command): [string, JsonObject] => [`recipe ${text(command.as)}`, command]),
        ),
        ...ofKind("graphty-results").flatMap((results) =>
            Object.entries((results.runs ?? {}) as Record<string, JsonObject>).map(
                ([id, run]): [string, JsonObject] => [`results ${id}`, run],
            ),
        ),
        ...ofKind("graphty-view").flatMap((view) =>
            ((view.runs ?? []) as JsonObject[]).map((run): [string, JsonObject] => [`view ${text(run.id)}`, run]),
        ),
        ...sections.flatMap((section) =>
            objectsIn(section.layers).flatMap((layer): [string, JsonObject][] => {
                const source = layer.source as JsonObject | undefined;
                return source?.by === "run" ? [[`layer source ${text(source.runId)}`, source]] : [];
            }),
        ),
    ];

    it("name every algorithm by its current key, and every param by a declared option", () => {
        const all = runs();
        assert.isAbove(all.length, 0);
        for (const [where, run] of all) {
            const entry = algorithms.get(run.algorithm as string);
            assert.isDefined(entry, `${where}: ${text(run.algorithm)}`);
            const declared = (entry.options as JsonObject[]).map((option) => option.name);
            for (const name of Object.keys((run.params ?? {}) as JsonObject)) {
                assert.include(declared, name, `${where} param`);
            }
        }
    });

    it("give every results field the name, kind and type the algorithm registry lists", () => {
        let checked = 0;
        for (const results of ofKind("graphty-results")) {
            for (const [id, run] of Object.entries((results.runs ?? {}) as Record<string, JsonObject>)) {
                const fields = new Map(
                    ((algorithms.get(run.algorithm as string)?.fields ?? []) as JsonObject[]).map((field) => [
                        field.name as string,
                        field,
                    ]),
                );
                for (const field of (run.fields ?? []) as JsonObject[]) {
                    const listed = fields.get(field.name as string);
                    assert.isDefined(listed, `${id} ${text(field.name)}`);
                    assert.deepEqual(field, pick(listed, ["name", "kind", "type"]), `${id} ${text(field.name)}`);
                    checked += 1;
                }
            }
        }

        assert.isAbove(checked, 0);
    });

    it("never save an option the dimension says in a layout record's own options", () => {
        const records = [...ofKind("graphty-recipe"), ...ofKind("graphty-results"), ...ofKind("graphty-view")]
            .flatMap((section) => [section.layout, ...((section.commands ?? []) as Json[])])
            .filter((each): each is JsonObject => typeof each === "object" && each !== null && !Array.isArray(each))
            .filter((each) => each.op === undefined || each.op === "layout.set");
        assert.isAbove(records.length, 0);
        for (const record of records) {
            const entry = layouts.get(record.id as string);
            const derived = ((entry?.options ?? []) as JsonObject[])
                .filter((option) => option.derivedFrom === "dimension")
                .map((option) => option.name as string);
            for (const name of Object.keys((record.options ?? {}) as JsonObject)) {
                assert.notInclude(derived, name, text(record.id));
            }
        }
    });

    it("set and encode only registry channels, through registry scales", () => {
        let checked = 0;
        for (const section of [...ofKind("graphty-style"), ...ofKind("graphty-view")]) {
            for (const layer of objectsIn(section.layers)) {
                for (const member of ["set", "encode"]) {
                    const held = layer[member];
                    if (typeof held !== "object" || held === null || Array.isArray(held)) {
                        continue;
                    }

                    for (const [channel, value] of Object.entries(held)) {
                        assert.isTrue(channels.has(channel), `${member} ${channel}`);
                        checked += 1;
                        const scale = member === "encode" ? (value as JsonObject).scale : undefined;
                        if (scale !== undefined) {
                            assert.isTrue(scales.has(scale), `scale ${text(scale)}`);
                        }
                    }
                }
            }
        }

        assert.isAbove(checked, 0);
    });

    it("name every layout, its options and its engine's options from the layout registry", () => {
        const records = [
            ...ofKind("graphty-recipe").flatMap((recipe) =>
                (recipe.commands as JsonObject[]).filter((command) => command.op === "layout.set"),
            ),
            ...[...ofKind("graphty-results"), ...ofKind("graphty-view")].flatMap((section) =>
                section.layout === undefined ? [] : [section.layout as JsonObject],
            ),
        ];
        assert.isAbove(records.length, 0);
        for (const record of records) {
            const entry = layouts.get(record.id as string);
            assert.isDefined(entry, text(record.id));
            const saved = (entry.options as JsonObject[]).map((option) => option.name);
            for (const name of Object.keys((record.options ?? {}) as JsonObject)) {
                assert.include(saved, name, `${text(record.id)} option`);
            }

            const drawnBy = record.drawnBy as JsonObject | undefined;
            if (drawnBy !== undefined) {
                const engine = (entry.engines as JsonObject[]).find((each) => each.engine === drawnBy.engine);
                assert.isDefined(engine, text(drawnBy.engine));
                for (const name of Object.keys((drawnBy.options ?? {}) as JsonObject)) {
                    assert.include(
                        (engine.options as JsonObject[]).map((option) => option.name),
                        name,
                        `${text(drawnBy.engine)} option`,
                    );
                }
            }
        }
    });
});
