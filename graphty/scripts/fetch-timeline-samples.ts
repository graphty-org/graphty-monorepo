/**
 * Downloads three real timed networks and writes them into public/samples/ as NetworkX node-link
 * JSON, every time an ISO 8601 UTC string on the edges (nodes follow their edges on the timeline):
 *
 * - campus-contacts.json: one week of Bluetooth proximity among university students (Copenhagen
 *   Networks Study, MIT license). One edge per pair per hour they were close, with `minutes`.
 * - graph-research.json: the largest connected group of co-authors in the Journal of Graph
 *   Algorithms and Applications, 1997 on (OpenAlex, CC0). One edge per co-author pair per paper,
 *   with `published` and `paper`.
 * - marvel-films.json: Marvel Cinematic Universe films and the actors cast in two or more of them
 *   (Wikidata, CC0). One edge per actor per film, with the film's `released` date.
 *
 * Unlike scripts/write-timeline-samples.ts this needs the network, and the OpenAlex and Wikidata
 * answers change as those databases are edited, so a rerun can differ. Downloads are cached in
 * ../tmp/timeline-sources/. Run: npm run samples:fetch (from graphty/).
 */

import { createHash } from "node:crypto";
import { createReadStream, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { createInterface } from "node:readline";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, "../public/samples");
const CACHE = resolve(HERE, "../../tmp/timeline-sources");
const AGENT = "graphty-samples/1.0 (https://graphty.app)";
const WARNING =
    "THIS FILE IS AUTO GENERATED: DO NOT EDIT THIS FILE. INSTEAD EDIT graphty/scripts/fetch-timeline-samples.ts";

interface Link {
    source: string;
    target: string;
    [key: string]: string | number;
}

/**
 * Downloads a URL once into the cache.
 * @param file - the cache file name.
 * @param url - the URL.
 * @param md5 - the expected MD5, when the source publishes one.
 * @returns the cached file's path.
 */
async function download(file: string, url: string, md5?: string): Promise<string> {
    const path = resolve(CACHE, file);
    if (!existsSync(path)) {
        mkdirSync(CACHE, { recursive: true });
        const response = await fetch(url, { headers: { "User-Agent": AGENT } });
        if (!response.ok) {
            throw new Error(`${url}: HTTP ${String(response.status)}`);
        }
        writeFileSync(path, Buffer.from(await response.arrayBuffer()));
    }
    if (md5 !== undefined) {
        const hash = createHash("md5"); // NOSONAR(S4790): checks a download against the MD5 its publisher lists
        if (hash.update(readFileSync(path)).digest("hex") !== md5) {
            throw new Error(`${file}: MD5 differs from the published ${md5}`);
        }
    }
    return path;
}

/**
 * Writes one sample.
 * @param file - the file name in public/samples.
 * @param graph - the graph's own attributes.
 * @param nodes - the nodes.
 * @param links - the edges.
 */
function write(file: string, graph: Record<string, string>, nodes: object[], links: Link[]): void {
    const doc = { directed: false, multigraph: true, graph: { note: WARNING, ...graph }, nodes, links };
    // Plain ASCII on disk: a name's accents are kept as JSON \u escapes.
    const json = JSON.stringify(doc).replaceAll(
        /[^\x20-\x7e]/g,
        (c) => `\\u${(c.codePointAt(0) ?? 0).toString(16).padStart(4, "0")}`, // NOSONAR(S7780): String.raw cannot hold \u before a substitution
    );
    writeFileSync(resolve(OUT, file), `${json}\n`);
    console.log(`wrote ${file}: ${String(nodes.length)} nodes, ${String(links.length)} edges`);
}

// ---------------------------------------------------------------------------------------------
// Copenhagen Networks Study: Bluetooth proximity
// ---------------------------------------------------------------------------------------------

/** The week kept: days 7 to 13 of the 28, Sunday to Saturday (day 0 is a Sunday). */
const FIRST_DAY = 7;
const DAYS = 7;
/** Close contact: RSSI of -70 dBm or stronger, roughly the same room. */
const MIN_RSSI = -70;
/** Kept when close in at least 3 of an hour's 12 five-minute scans. */
const MIN_SCANS = 3;
/**
 * The study published seconds since its start (a Sunday, 00:00 local time), not dates. The week
 * is placed on a stand-in Sunday so the timeline reads in weekdays and hours.
 */
const STAND_IN_SUNDAY = Date.UTC(2024, 1, 4);

/** Writes campus-contacts.json. */
async function campusContacts(): Promise<void> {
    const bt = await download(
        "cns-bt_symmetric.csv",
        "https://ndownloader.figshare.com/files/14000795",
        "98892459f73e774cf79e7977edfeee3e",
    );
    const genders = await download(
        "cns-genders.csv",
        "https://ndownloader.figshare.com/files/13389440",
        "eb033aae23fff859684a82d00ffd8099",
    );
    const start = FIRST_DAY * 86_400;
    const end = start + DAYS * 86_400;
    const scans = new Map<string, number>();
    for await (const line of createInterface({ input: createReadStream(bt) })) {
        if (line.startsWith("#")) {
            continue;
        }
        const [t, a, b, rssi] = line.split(",").map(Number);
        if (b < 0 || rssi < MIN_RSSI || t < start || t >= end) {
            continue;
        }
        const key = `${String(Math.min(a, b))},${String(Math.max(a, b))},${String(Math.floor((t - start) / 3600))}`;
        scans.set(key, (scans.get(key) ?? 0) + 1);
    }
    const links: Link[] = [];
    const seen = new Set<number>();
    for (const [key, count] of scans) {
        if (count < MIN_SCANS) {
            continue;
        }
        const [a, b, hour] = key.split(",").map(Number);
        seen.add(a).add(b);
        const time = new Date(STAND_IN_SUNDAY + hour * 3_600_000).toISOString().replace(".000Z", "Z");
        links.push({ source: `s${String(a)}`, target: `s${String(b)}`, time, minutes: count * 5 });
    }
    links.sort((x, y) => x.time.toString().localeCompare(y.time.toString()));
    const gender = new Map<number, string>();
    for (const line of readFileSync(genders, "utf8").split("\n")) {
        const [user, female] = line.split(",");
        if (!line.startsWith("#") && female !== undefined) {
            gender.set(Number(user), female.trim() === "1" ? "female" : "male");
        }
    }
    const nodes = [...seen]
        .sort((x, y) => x - y)
        .map((user) => ({
            id: `s${String(user)}`,
            name: `Student ${String(user)}`,
            ...(gender.has(user) ? { gender: gender.get(user) } : {}),
        }));
    write(
        "campus-contacts.json",
        {
            source: "Copenhagen Networks Study interaction data, https://doi.org/10.6084/m9.figshare.7267433",
            citation:
                "Sapiezynski, Stopczynski, Lassen and Lehmann, Interaction data from the Copenhagen Networks Study, Scientific Data 6, 315 (2019)",
            license: "MIT",
            time: "Hours of a stand-in week: the study published time since its start, a Sunday",
        },
        nodes,
        links,
    );
}

// ---------------------------------------------------------------------------------------------
// OpenAlex: Journal of Graph Algorithms and Applications co-authorship
// ---------------------------------------------------------------------------------------------

interface Work {
    readonly id: string;
    readonly title: string | null;
    readonly publication_date: string;
    readonly type: string;
    readonly authorships: readonly { readonly author: { readonly id: string | null; readonly display_name: string } }[];
}

/** OpenAlex pages hold at most 200 works, and paging further needs a key: ask by years instead. */
const JGAA_YEARS = ["1990-2004", "2005-2011", "2012-2014", "2015-2017", "2018-2021", "2022-2030"];

/** Writes graph-research.json. */
async function graphResearch(): Promise<void> {
    const works: Work[] = [];
    for (const years of JGAA_YEARS) {
        const url = new URL("https://api.openalex.org/works");
        url.searchParams.set("filter", `primary_location.source.id:S33451491,publication_year:${years}`);
        url.searchParams.set("select", "id,title,publication_date,type,authorships");
        url.searchParams.set("per-page", "200");
        const page = JSON.parse(readFileSync(await download(`jgaa-${years}.json`, url.href), "utf8")) as {
            meta: { count: number };
            results: Work[];
        };
        if (page.results.length !== page.meta.count) {
            throw new Error(`JGAA ${years}: ${String(page.meta.count)} works, more than one page`);
        }
        works.push(...page.results);
    }
    const names = new Map<string, string>();
    const links: Link[] = [];
    for (const work of works.filter((each) => each.type === "article")) {
        const authors = [
            ...new Map(
                work.authorships.flatMap(({ author }) =>
                    author.id === null ? [] : [[author.id.replace("https://openalex.org/", ""), author.display_name]],
                ),
            ),
        ].sort(([x], [y]) => x.localeCompare(y));
        for (let i = 0; i < authors.length; i++) {
            for (let j = i + 1; j < authors.length; j++) {
                names.set(authors[i][0], authors[i][1]).set(authors[j][0], authors[j][1]);
                links.push({
                    source: authors[i][0],
                    target: authors[j][0],
                    published: work.publication_date,
                    paper: work.title ?? work.id,
                });
            }
        }
    }
    // Only the largest connected group of co-authors: the 150 or so small groups (one paper's
    // authors each) ring the drawing and say nothing about how the community grew.
    const parent = new Map([...names.keys()].map((id) => [id, id]));
    const root = (id: string): string => {
        let at = id;
        while (parent.get(at) !== at) {
            at = parent.get(at) ?? at;
        }
        return at;
    };
    for (const link of links) {
        parent.set(root(link.source), root(link.target));
    }
    const sizes = new Map<string, number>();
    for (const id of names.keys()) {
        sizes.set(root(id), (sizes.get(root(id)) ?? 0) + 1);
    }
    const entries = [...sizes];
    const largest = entries.reduce((best, each) => (each[1] > best[1] ? each : best), entries[0])[0];
    const kept = links.filter((link) => root(link.source) === largest);
    kept.sort((x, y) => x.published.toString().localeCompare(y.published.toString()));
    const nodes = [...names]
        .filter(([id]) => root(id) === largest)
        .sort(([x], [y]) => x.localeCompare(y))
        .map(([id, name]) => ({ id, name }));
    write(
        "graph-research.json",
        {
            source: "OpenAlex, works in source S33451491 (Journal of Graph Algorithms and Applications), https://openalex.org",
            citation:
                "Priem, Piwowar and Orr, OpenAlex: A fully-open index of scholarly works, authors, venues, institutions, and concepts (2022), https://arxiv.org/abs/2205.01833",
            license: "CC0 1.0",
        },
        nodes,
        kept,
    );
}

// ---------------------------------------------------------------------------------------------
// Wikidata: Marvel Cinematic Universe films and their recurring cast
// ---------------------------------------------------------------------------------------------

/** Films of the MCU film series (Q642878) with their earliest release date and cast. */
const MCU_QUERY = `SELECT ?film ?filmLabel (MIN(?date) AS ?released) ?actor ?actorLabel WHERE {
  ?film wdt:P179 wd:Q642878; wdt:P31 wd:Q11424; wdt:P577 ?date; wdt:P161 ?actor.
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en,mul". }
} GROUP BY ?film ?filmLabel ?actor ?actorLabel`;

/** A cut of a film already listed, not a film of its own. */
const RE_RELEASES = new Set(["Q113471777"]);

/** Writes marvel-films.json. */
async function marvelFilms(): Promise<void> {
    const url = new URL("https://query.wikidata.org/sparql");
    url.searchParams.set("query", MCU_QUERY);
    url.searchParams.set("format", "json");
    const rows = (
        JSON.parse(readFileSync(await download("mcu.json", url.href), "utf8")) as {
            results: { bindings: Record<string, { value: string }>[] };
        }
    ).results.bindings.map((row) => ({
        film: row.film.value.replace("http://www.wikidata.org/entity/", ""), // NOSONAR(S5332): Wikidata's entity IRI prefix, an identifier, never fetched
        filmName: row.filmLabel.value,
        released: row.released.value.slice(0, 10),
        actor: row.actor.value.replace("http://www.wikidata.org/entity/", ""), // NOSONAR(S5332): Wikidata's entity IRI prefix, an identifier, never fetched
        actorName: row.actorLabel.value,
    }));
    const kept = rows.filter((row) => !RE_RELEASES.has(row.film));
    const films = new Map<string, number>();
    for (const row of kept) {
        films.set(row.actor, (films.get(row.actor) ?? 0) + 1);
    }
    // ponytail: actors in one film only are left out; they are most of the cast and would bury the bridges.
    const recurring = kept.filter((row) => (films.get(row.actor) ?? 0) >= 2);
    const nodes = new Map<string, object>();
    const links: Link[] = [];
    for (const row of recurring) {
        nodes.set(row.film, { id: row.film, name: row.filmName, kind: "film" });
        nodes.set(row.actor, { id: row.actor, name: row.actorName, kind: "actor", films: films.get(row.actor) });
        links.push({ source: row.actor, target: row.film, released: row.released });
    }
    links.sort(
        (x, y) =>
            x.released.toString().localeCompare(y.released.toString()) ||
            x.source.localeCompare(y.source) ||
            x.target.localeCompare(y.target),
    );
    write(
        "marvel-films.json",
        {
            source: "Wikidata, films in the Marvel Cinematic Universe film series (Q642878) and their cast members (P161), https://www.wikidata.org",
            license: "CC0 1.0",
        },
        [...nodes.values()].sort((x, y) => (x as { id: string }).id.localeCompare((y as { id: string }).id)),
        links,
    );
}

await campusContacts();
await graphResearch();
await marvelFilms();
