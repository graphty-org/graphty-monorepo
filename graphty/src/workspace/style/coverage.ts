/**
 * Why a property the Style tab draws has no vary glyph. These are decisions, not omissions: the
 * coverage test fails when a drawn property has neither a vary glyph nor a reason here.
 */
const VARY_DECISIONS = {
    yesOrNo:
        "A yes-or-no property (wireframe, show, curved) has no vary by: picking which elements are on is what Which elements does, so a layer for those elements sets it",
    look: "A label's look is a set of fields, each set in its settings; its size, text color and background vary through their own properties",
    opacity:
        "Opacity varies by a value from its own field in the color's settings pop-out (Color, Line, Ends, Halo and Band settings), shown as a percent",
    shader: "A shader is picked from the gallery, not varied: what varies per element is its parameters declared 'varies', each bound from the shader's settings pop-out",
} as const;

/**
 * The drawn properties with no vary glyph, each with its decision; a yes-or-no property needs no
 * entry, its kind is its reason ({@link noVaryReason}). Every other drawn property varies by a value; an opacity varies from its settings pop-out ({@link VARY_DECISIONS}.opacity).
 */
const NO_VARY: Readonly<Partial<Record<Channel, string>>> = {
    "node.labelStyle": VARY_DECISIONS.look,
    "node.tooltipStyle": VARY_DECISIONS.look,
    "edge.labelStyle": VARY_DECISIONS.look,
    "edge.arrowHeadTextStyle": VARY_DECISIONS.look,
    "edge.arrowTailTextStyle": VARY_DECISIONS.look,
    "node.xlabelStyle": VARY_DECISIONS.look,
    "edge.xlabelStyle": VARY_DECISIONS.look,
    "node.shaders": VARY_DECISIONS.shader,
    "edge.shaders": VARY_DECISIONS.shader,
};

/**
 * Why a drawn property has no vary glyph, or undefined when it varies: its decision in
 * {@link NO_VARY}, else, for any yes-or-no property, {@link VARY_DECISIONS}.yesOrNo by its kind.
 * @param descriptor - the property.
 * @returns the decision, or undefined.
 */
export function noVaryReason(descriptor: Pick<ChannelDescriptor, "channel" | "accepts">): string | undefined {
    return NO_VARY[descriptor.channel] ?? (descriptor.accepts === "boolean" ? VARY_DECISIONS.yesOrNo : undefined);
}

