#!/usr/bin/env node
/**
 * Builds alzheimer-network.json: the human proteins most strongly linked to Alzheimer's disease
 * (Open Targets, CC0) plus the targets of approved and phase 3 Alzheimer's drugs, joined by their
 * high-confidence STRING interactions (CC BY 4.0). Node-link JSON, as graph-io reads it.
 *
 *   node tools/demo-video/data/round2/make-alzheimer.mjs [--top 300] [--score 0.7]
 *
 * Re-running fetches the live Open Targets release, so the file can change between releases;
 * STRING is pinned to version 12.5.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";

const { values: o } = parseArgs({
    options: { top: { type: "string", default: "300" }, score: { type: "string", default: "0.7" } },
});
const TOP = Number(o.top);
const MIN_SCORE = Number(o.score);
const DISEASE = "MONDO_0004975"; // Alzheimer disease
const OT = "https://api.platform.opentargets.org/api/v4/graphql";
const STRING = "https://version-12-5.string-db.org/api";
const OUT = join(import.meta.dirname, "alzheimer-network.json");

async function ot(query) {
    const r = await fetch(OT, {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ query }),
    });
    if (!r.ok) throw new Error(`Open Targets ${r.status}`);
    const j = await r.json();
    if (j.errors) throw new Error(JSON.stringify(j.errors));
    return j.data;
}

// stage order, most advanced last
const STAGES = ["PHASE_1", "PHASE_1_2", "PHASE_2", "PHASE_2_3", "PHASE_3", "APPROVAL"];
const STAGE_WORDS = { PHASE_3: "Phase 3", APPROVAL: "Approved" };

const assoc = await ot(`{ disease(efoId:"${DISEASE}"){ associatedTargets(page:{index:0,size:${TOP}}){ rows{ score
    target{ approvedSymbol approvedName genomicLocation{ chromosome } } } } } }`);
const drugs = await ot(`{ disease(efoId:"${DISEASE}"){ drugAndClinicalCandidates{ rows{ maxClinicalStage
    drug{ name mechanismsOfAction{ rows{ targets{ approvedSymbol approvedName genomicLocation{ chromosome } } } } } } } } }`);

const genes = new Map(); // symbol -> node
const node = (t) => {
    if (!genes.has(t.approvedSymbol))
        genes.set(t.approvedSymbol, {
            id: t.approvedSymbol,
            label: t.approvedSymbol,
            name: t.approvedName,
            chromosome: t.genomicLocation?.chromosome ? `chr${t.genomicLocation.chromosome}` : "",
            association: 0,
            drug: "",
            drugStage: "",
        });
    return genes.get(t.approvedSymbol);
};
for (const r of assoc.disease.associatedTargets.rows) node(r.target).association = +r.score.toFixed(3);
for (const r of drugs.disease.drugAndClinicalCandidates.rows) {
    const stage = STAGES.indexOf(r.maxClinicalStage);
    if (stage < STAGES.indexOf("PHASE_3")) continue;
    for (const m of r.drug.mechanismsOfAction?.rows ?? [])
        for (const t of m.targets) {
            const n = node(t);
            if (stage > (n.stageIndex ?? -1)) {
                n.stageIndex = stage;
                n.drugStage = STAGE_WORDS[r.maxClinicalStage];
                n.drug = titleCase(r.drug.name);
            }
        }
}
for (const n of genes.values()) delete n.stageIndex;
function titleCase(s) {
    return s.toLowerCase().replaceAll(/\b[a-z]/g, (c) => c.toUpperCase());
}

const body = new URLSearchParams({
    identifiers: [...genes.keys()].join("\r"),
    species: "9606",
    required_score: String(Math.round(MIN_SCORE * 1000)),
    caller_identity: "graphty-demo-video",
});
const r = await fetch(`${STRING}/tsv/network`, { method: "POST", body });
if (!r.ok) throw new Error(`STRING ${r.status}`);
const rows = (await r.text()).trim().split("\n").slice(1);
const links = [];
const seen = new Set();
for (const row of rows) {
    const [, , a, b, , score] = row.split("\t");
    const key = [a, b].sort().join("|");
    if (a === b || seen.has(key) || !genes.has(a) || !genes.has(b)) continue;
    seen.add(key);
    links.push({ source: a, target: b, confidence: +score });
}
// only proteins with at least one interaction: an unconnected protein says nothing in this story
const linked = new Set(links.flatMap((l) => [l.source, l.target]));
const nodes = [...genes.values()].filter((n) => linked.has(n.id));
writeFileSync(
    OUT,
    JSON.stringify(
        {
            directed: false,
            multigraph: false,
            graph: {
                note: "Generated by tools/demo-video/data/round2/make-alzheimer.mjs",
                source: `Open Targets Platform (disease ${DISEASE}, associated targets and drug candidates); STRING v12.5 interactions, confidence >= ${MIN_SCORE}`,
                license: "Open Targets data CC0 1.0; STRING CC BY 4.0 (Szklarczyk et al., Nucleic Acids Res. 2023)",
            },
            nodes,
            links,
        },
        null,
        0,
    ) + "\n",
);
console.log(`${nodes.length} proteins, ${links.length} interactions -> ${OUT}`);
