// Tests of tools/dependency-refresh.mjs on a throwaway fixture repository: pnpm, visual-review init and the
// tag lookup are stand-ins, git is real.
//
//   node --test tools/dependency-refresh.test.mjs
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { after, describe, it } from "node:test";

import { bumpActionRefs, openPullRequest, update } from "./dependency-refresh.mjs";
import { isolateGit } from "./isolated-git-env.mjs";

isolateGit();
const dirs = [];
after(() => dirs.forEach((d) => rmSync(d, { recursive: true, force: true })));

const TEMPLATE = "steps:\n  - uses: foo/bar@v1.2.3\n  - uses: actions/checkout@v4\n";
const generate = (template) => `# Generated by visual-review init\n${template}`;

function fixture() {
    const cwd = mkdtempSync(join(tmpdir(), "dep-refresh-"));
    dirs.push(cwd);
    const files = {
        "package.json": JSON.stringify({ devDependencies: { a: "^1.2.0", b: "~2.0.0" } }),
        "pnpm-lock.yaml": "a: 1.2.0\n",
        ".github/workflows/w.yml":
            "steps:\n  - uses: foo/bar/sub@v1.2\n  - uses: x/y@3d3c42e5aac5ba805825da76410c181273ba90b1\n",
        "visual-review/templates/visual-seed.yml": TEMPLATE,
        ".github/workflows/visual-seed.yml": generate(TEMPLATE),
    };
    for (const [f, text] of Object.entries(files)) {
        mkdirSync(dirname(join(cwd, f)), { recursive: true });
        writeFileSync(join(cwd, f), text);
    }
    execFileSync("git", ["init", "-q", "-b", "master"], { cwd });
    execFileSync("git", ["add", "."], { cwd });
    execFileSync("git", ["commit", "-qm", "init"], { cwd });
    const origin = mkdtempSync(join(tmpdir(), "dep-refresh-origin-"));
    dirs.push(origin);
    execFileSync("git", ["init", "-q", "--bare", origin]);
    execFileSync("git", ["remote", "add", "origin", origin], { cwd });
    return cwd;
}

/**
 * A command runner: `pnpm update` applies `bump` to package.json, init renders the template, git is real.
 * @param cwd the fixture
 * @param o options
 * @param o.bump what `pnpm update` does to the devDependencies
 * @param o.calls receives every command line
 * @param o.fail which commands fail
 * @returns the runner
 */
const runner =
    (cwd, { bump = (deps) => deps, calls = [], fail = () => false } = {}) =>
    (cmd, args, opts) => {
        calls.push([cmd, ...args].join(" "));
        if (fail(cmd, args)) throw new Error(`refused: ${cmd} ${args.join(" ")}`);
        if (cmd === "pnpm" && args[0] === "update") {
            const pkg = JSON.parse(readFileSync(join(cwd, "package.json"), "utf8"));
            const next = bump({ ...pkg.devDependencies });
            if (JSON.stringify(next) !== JSON.stringify(pkg.devDependencies)) {
                writeFileSync(join(cwd, "package.json"), JSON.stringify({ devDependencies: next }));
                writeFileSync(join(cwd, "pnpm-lock.yaml"), `a: ${next.a.slice(1)}\n`);
            }
            return "";
        }
        if (cmd === "pnpm" && args.join(" ") === "exec visual-review init") {
            const template = readFileSync(join(cwd, "visual-review/templates/visual-seed.yml"), "utf8");
            writeFileSync(join(cwd, ".github/workflows/visual-seed.yml"), generate(template));
            return "";
        }
        if (cmd === "gh") return args[1] === "create" ? "https://github.com/o/r/pull/1\n" : "";
        return execFileSync(cmd, args, { encoding: "utf8", ...opts, stdio: ["ignore", "pipe", "pipe"] });
    };

const tags = { "foo/bar": ["v1.2.3", "v1.4.0", "v1.4", "v1.10", "v2.0.0", "v2.1"] };
const tagsOf = (repo) => tags[repo] ?? [];

describe("dependency-refresh", () => {
    it("moves an action to the newest tag of its major, keeping its precision, and leaves majors and pins", () => {
        assert.equal(bumpActionRefs("- uses: foo/bar@v1.2.3", tagsOf), "- uses: foo/bar@v1.4.0");
        assert.equal(bumpActionRefs("uses: foo/bar/sub@v1.2", tagsOf), "uses: foo/bar/sub@v1.10");
        assert.equal(bumpActionRefs("uses: foo/bar@v2.1", tagsOf), "uses: foo/bar@v2.1");
        assert.equal(bumpActionRefs("uses: foo/bar@v1", tagsOf), "uses: foo/bar@v1");
        const pin = "uses: foo/bar@3d3c42e5aac5ba805825da76410c181273ba90b1";
        assert.equal(bumpActionRefs(pin, tagsOf), pin);
    });

    it("updates npm within ranges and actions within majors, and regenerates visual-seed.yml from the template", () => {
        const cwd = fixture();
        const calls = [];
        const run = runner(cwd, { calls, bump: (d) => ({ ...d, a: "^1.4.0" }) });
        const { npm, actions } = update({ cwd, run, tagsOf });
        assert.ok(calls.includes("pnpm update --recursive"), "never --latest: that would cross majors");
        assert.ok(!calls.some((c) => c.includes("--latest")));
        assert.deepEqual(npm.sort(), ["package.json", "pnpm-lock.yaml"]);
        assert.deepEqual(actions.sort(), [
            ".github/workflows/visual-seed.yml",
            ".github/workflows/w.yml",
            "visual-review/templates/visual-seed.yml",
        ]);
        const read = (f) => readFileSync(join(cwd, f), "utf8");
        assert.match(read(".github/workflows/w.yml"), /foo\/bar\/sub@v1\.10\n/);
        assert.match(read("visual-review/templates/visual-seed.yml"), /foo\/bar@v1\.4\.0\n/);
        assert.match(read("visual-review/templates/visual-seed.yml"), /actions\/checkout@v4\n/);
        // the generated file is the regenerated template, not an edit of its own
        assert.equal(
            read(".github/workflows/visual-seed.yml"),
            generate(read("visual-review/templates/visual-seed.yml")),
        );
    });

    it("stops when a specifier's major moved", () => {
        const cwd = fixture();
        const run = runner(cwd, { bump: (d) => ({ ...d, b: "~3.0.0" }) });
        assert.throws(() => update({ cwd, run, tagsOf }), /a major moved.*package\.json b/);
    });

    it("changes nothing and opens nothing when nothing is newer", () => {
        const cwd = fixture();
        const calls = [];
        const run = runner(cwd, { calls });
        const result = update({ cwd, run, tagsOf: () => [] });
        assert.deepEqual(result, { npm: [], actions: [] });
        assert.equal(openPullRequest({ cwd, label: "x", ...result, run }), null);
        assert.ok(!calls.some((c) => c.startsWith("gh")));
    });

    it("opens one pull request, and pushes the npm commit alone when the workflow changes are refused", () => {
        const cwd = fixture();
        const calls = [];
        const fail = (cmd, args) => cmd === "git" && args[0] === "push" && args.at(-1).startsWith("HEAD:");
        const run = runner(cwd, { calls, fail, bump: (d) => ({ ...d, a: "^1.4.0" }) });
        const { npm, actions } = update({ cwd, run, tagsOf });
        const url = openPullRequest({ cwd, label: "graphty@1.2.3", npm, actions, run });
        assert.equal(url, "https://github.com/o/r/pull/1");
        const log = execFileSync("git", ["log", "--format=%s", "-3"], { cwd, encoding: "utf8" }).trim().split("\n");
        assert.deepEqual(log, [
            "chore(deps): GitHub Actions minor and patch bumps after promotion graphty@1.2.3",
            "chore(deps): refresh dependencies after promotion graphty@1.2.3",
            "init",
        ]);
        const pushed = execFileSync("git", ["log", "--format=%s", "-1", "chore/deps-refresh-graphty-1.2.3"], {
            cwd: execFileSync("git", ["remote", "get-url", "origin"], { cwd, encoding: "utf8" }).trim(),
            encoding: "utf8",
        });
        assert.equal(pushed.trim(), log[1]);
        const create = calls.find((c) => c.startsWith("gh pr create"));
        assert.match(create, /--title chore\(deps\): refresh dependencies after promotion graphty@1\.2\.3/);
        assert.match(create, /\nNo issue\n/);
        assert.match(create, /\n## Proof\n/);
        assert.match(create, /were not pushed/);
        assert.ok(calls.includes("gh pr merge --auto --merge https://github.com/o/r/pull/1"));
    });
});
